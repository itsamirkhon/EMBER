export function useAsync<X>(fn: () => Promise<X>, deps: unknown[]) {
  const [state, setState] = useState<{ data: X | null; error: ApiError | null; loading: boolean }>({ data: null, error: null, loading: true });
  const [tick, setTick] = useState(0);
  useEffect(() => {
    let live = true;
    setState((s) => ({ ...s, loading: true, error: null }));
    fn().then((data) => live && setState({ data, error: null, loading: false }),
      (e) => live && setState({ data: null, error: e instanceof ApiError ? e : new ApiError(0, 'error', String(e)), loading: false }));
    return () => { live = false; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [...deps, tick]);
  const reload = useCallback(() => setTick((t) => t + 1), []);
  return { ...state, reload };
}

export function ErrorBanner({ error, onRetry }: { error: unknown; onRetry?: () => void }) {
  if (!error) return null;
  const e = error instanceof ApiError ? error : null;
  return (
    <div className="banner error" role="alert">
      <strong>{e ? `Error${e.code ? ` (${e.code})` : ''}` : 'Error'}</strong>
      {e ? e.message : String(error)}
      {onRetry && <div style={{ marginTop: 8 }}><button className="btn" onClick={onRetry}>Retry</button></div>}
    </div>
  );
}
export function Loading({ label = 'Loading' }: { label?: string }) {
  return <p className="muted" role="status"><span className="spinner" aria-hidden /> {label}…</p>;
}
export function Async<X>({ r, children, label }: { r: { data: X | null; error: ApiError | null; loading: boolean; reload: () => void }; children: (d: X) => ReactNode; label?: string }) {
  if (r.error) return <ErrorBanner error={r.error} onRetry={r.reload} />;
  if (r.loading || r.data === null) return <Loading label={label} />;
  return <div className="fade-in">{children(r.data)}</div>;
}

const MODE_LABEL: Record<Mode, string> = { live_ai: 'Live AI', deterministic: 'Deterministic', saved_example: 'Saved example' };
const MODE_TIP: Record<Mode, string> = {
  live_ai: 'Explanation text was generated by an AI model from the evidence package.',
  deterministic: 'Explanation text was built by rules from the evidence package. No AI model was used.',
  saved_example: 'This is a stored example review, not a fresh run.',
};
export function ModeBadge({ mode }: { mode: Mode }) {
  return <span className={`badge ${mode === 'live_ai' ? 'accent' : mode === 'saved_example' ? 'info' : ''}`} title={MODE_TIP[mode]} data-testid="mode-badge">Mode: {MODE_LABEL[mode]}</span>;
}
export function VerificationBadge({ v }: { v: string }) {
  const prov = v === 'provisional';
  return <span className={`badge ${prov ? 'warn' : 'ok'}`} title={prov ? 'Not yet checked against the cited document.' : 'Checked against the cited document.'}>{prov ? 'Provisional' : v}</span>;
}
export const Badge = ({ children, tone = '' }: { children: ReactNode; tone?: '' | 'ok' | 'warn' | 'bad' | 'info' | 'accent' }) => <span className={`badge ${tone}`}>{children}</span>;

export function Unknown({ what }: { what?: string }) {
  return <span className="unknown-val" title={what ? `${what}: not recorded in the cited source` : 'Not recorded in the cited source'}>unknown</span>;
}
/** Renders a ScientificValue. Unknown values are always the literal word "unknown", never 0 or blank. */
export function Sv({ v, showKind = true }: { v: ScientificValue | null | undefined; showKind?: boolean }) {
  if (!v || v.kind === 'unknown' || v.value === null || v.value === '') return <Unknown />;
  const ref = v.source_ref;
  return (
    <span title={ref ? `${ref.source_id} ${ref.locator}` : undefined}>
      {String(v.value)}{v.unit ? ` ${v.unit}` : ''}
      {v.role && <span className="dim small"> ({v.role})</span>}
      {(showKind || v.kind === 'assumed') && <span className="sv-kind" style={v.kind === 'assumed' ? { color: 'var(--warn)' } : undefined}>{v.kind}</span>}
    </span>
  );
}
export function fmt(x: unknown): string {
  if (x === null || x === undefined || x === '') return '';
  if (typeof x === 'object') return Array.isArray(x) ? x.map(fmt).join(', ') : Object.entries(x as Record<string, unknown>).map(([k, v]) => `${pretty(k)}: ${fmt(v) || 'unknown'}`).join('; ');
  return String(x);
}
/** Any value; null/empty is shown as "unknown", objects are flattened to readable text. */
export const Val = ({ x, what }: { x: unknown; what?: string }) => (fmt(x) === '' ? <Unknown what={what} /> : <>{fmt(x)}</>);
export function Conds({ c }: { c: Record<string, unknown> }) {
  const e = Object.entries(c);
  if (!e.length) return <Unknown what="conditions" />;
  return <span className="cond-list">{e.map(([k, v]) => <span key={k} className="badge" title={pretty(k)}>{pretty(k)}: {fmt(v) || <span className="unknown-val">unknown</span>}</span>)}</span>;
}

export function Quote({ s }: { s: SourceRef }) {
  return (
    <div>
      <div className="small"><a href={s.url} target="_blank" rel="noreferrer noopener">{s.source_id}</a>{s.locator && <span className="dim"> · {s.locator}</span>}</div>
      {s.quote ? <blockquote className="quote">{s.quote}</blockquote> : <span className="dim small">no quote fragment stored</span>}
    </div>
  );
}
export function Expand({ summary, children, open }: { summary: ReactNode; children: ReactNode; open?: boolean }) {
  return <details className="exp" open={open}><summary>{summary}</summary><div className="body">{children}</div></details>;
}
export function Field({ id, label, hint, children, unknown }: { id: string; label: string; hint?: string; children: ReactNode; unknown?: boolean }) {
  return <div className={`field${unknown ? ' unknown' : ''}`}><label htmlFor={id}>{label}</label>{children}{hint && <div className="hint">{hint}</div>}</div>;
}
export function Disclaimer({ children, tone = 'info' }: { children: ReactNode; tone?: 'info' | 'warn' }) {
  return <div className={`banner ${tone}`} role="note">{children}</div>;
}
export const pct = (n: number) => `${Math.round(n * 100)}%`;
export const pretty = (s: string) => s.replace(/_/g, ' ');
export function KV({ rows }: { rows: [string, ReactNode][] }) {
  return <dl className="kv">{rows.map(([k, v]) => <Fragment key={k}><dt>{k}</dt><dd>{v}</dd></Fragment>)}</dl>;
}
export function download(name: string, text: string, type: string) {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement('a'); a.href = url; a.download = name; a.click(); URL.revokeObjectURL(url);
}
